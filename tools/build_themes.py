"""Validate installed theme manifests and generate a static browser registry."""
import json
import math
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'assets/themes'
STATES = set('R P Sc L Sp H Hs Hi Z Zi Zh Zc Za'.split())
KINDS = set('rock paper scissors lizard spock human zombie'.split())


def require(condition, detail):
    if not condition:
        raise ValueError(detail)


def asset(root, name, suffix):
    require(isinstance(name, str) and re.fullmatch(r'[\w./-]+', name, re.ASCII), f'Invalid path {name}')
    require(not any(part in ('', '.', '..') for part in name.split('/')), f'Invalid path {name}')
    path = (root / name).resolve()
    require(path.is_relative_to(root.resolve()) and path.suffix == suffix and path.is_file(), f'Invalid resource {name}')
    return path


def number(value, lo, hi):
    return type(value) in (int, float) and math.isfinite(value) and lo <= value <= hi


def build(root=ROOT):
    result = {}
    for path in sorted(root.glob('*/theme.json')):
        manifest = json.loads(path.read_text())
        key = manifest['id']
        require(path.resolve().is_relative_to(root.resolve()), 'Manifest outside registry')
        require(key == path.parent.name and re.fullmatch(r'[a-z][a-z0-9-]*', key) and key not in result, 'Invalid or duplicate theme ID')
        require(type(manifest['schemaVersion']) is int and manifest['schemaVersion'] == 1, 'Unsupported schema')
        require(isinstance(manifest['displayName'], str) and manifest['displayName'].strip(), 'Missing name')
        require(manifest['fallback'] == 'base-classic-placeholder', 'Unknown fallback')
        sheet = asset(path.parent, manifest['stylesheet'], '.css')
        css = re.sub(r'/\*.*?\*/', '', sheet.read_text(), flags=re.S)
        require(not re.search(r'@import\b', css, re.I), 'Bundle theme CSS into one stylesheet')
        for match in re.finditer(r'url\(\s*([^)]*?)\s*\)', css, re.I):
            name = match.group(1).strip('\"\'')
            if re.fullmatch(r'#[\w-]+', name):
                continue
            suffix = Path(name).suffix
            require(suffix in ('.woff2', '.png'), 'Unsupported CSS asset')
            asset(path.parent, str(sheet.parent.relative_to(path.parent) / name), suffix)
        require(set(manifest['categoryColors']) == KINDS, 'Incomplete palette')
        for colors in ('categoryColors', 'nameColors', 'outlineColors'):
            require(all(k in KINDS and re.fullmatch(r'#[0-9a-fA-F]{6}', v) for k,v in manifest.get(colors, {}).items()), 'Invalid colors')
        states = manifest['states']
        require(set(states) <= STATES and (key != 'classic' or set(states) == STATES), 'Invalid state mapping')
        for state in states.values():
            require(len(state['pivot']) == 2 and all(number(x, 0, 1) for x in state['pivot']), 'Invalid pivot')
            require(number(state['fps'], 0.1, 120) and number(state['facingDegrees'], -360, 360), 'Invalid animation')
            require(isinstance(state['frames'], list) and state['frames'], 'No frames')
            sizes = []
            for name in state['frames']:
                with asset(path.parent, name, '.png').open('rb') as img:
                    header = img.read(24)
                require(header[:8] == b'\x89PNG\r\n\x1a\n' and header[12:16] == b'IHDR', 'Invalid PNG')
                sizes.append(struct.unpack('>II', header[16:24]))
            require(len(set(sizes)) == 1 and all(sizes[0]), 'Frame sizes must match')
            state['size'] = sizes[0]
        result[key] = manifest
    require('classic' in result, 'Missing Classic')
    return result


if __name__ == '__main__':
    registry = build()
    (ROOT / 'registry.js').write_text('// Generated by tools/build_themes.py\nwindow.SwarmRegistry = ' + json.dumps(registry, indent=2) + ';\n')
